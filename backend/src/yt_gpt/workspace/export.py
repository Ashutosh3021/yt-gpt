"""Regenerate ``transcripts.md`` from the authoritative data."""

from __future__ import annotations

from typing import Any

from ..util import format_seconds, iso_now


def _marker_lines(text: str) -> list[str]:
    """Split clean transcript text into paragraphs, preserving sparse markers."""
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    return lines


def render_workspace_markdown(name: str, videos: list[dict[str, Any]]) -> str:
    ready = [v for v in videos if v.get("status") == "ready"]
    total_tokens = sum(int(v.get("tokens") or 0) for v in ready)
    out: list[str] = [
        f"# {name}",
        "",
        f"_Generated by yt-gpt on {iso_now()}_",
        "",
        f"{len(ready)} videos · about {total_tokens:,} tokens",
        "",
        "---",
        "",
    ]
    for index, video in enumerate(ready, start=1):
        out.append(f"## {index}. {video.get('title') or video.get('youtubeId')}")
        out.append("")
        out.append(f"- Channel: {video.get('channel') or 'unknown'}")
        out.append(f"- URL: {video.get('url')}")
        out.append(f"- Duration: {format_seconds(float(video.get('durationS') or 0))}")
        out.append(f"- Transcript source: {video.get('transcriptSource') or 'unknown'}")
        if video.get("tokens"):
            out.append(f"- Tokens (estimated): {int(video['tokens']):,}")
        out.append("")
        segments = video.get("segments") or []
        if segments:
            last_marker = -1000.0
            for segment in segments:
                start = float(segment.get("start") or 0)
                text = str(segment.get("text") or "").strip()
                if not text:
                    continue
                if start - last_marker >= 45:
                    out.append(f"[{format_seconds(start)}] {text}")
                    last_marker = start
                else:
                    out.append(text)
            out.append("")
        else:
            out.append("_No transcript segments are available._")
            out.append("")
    return "\n".join(out).rstrip() + "\n"
